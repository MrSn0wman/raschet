# -*- coding: utf-8 -*-
"""Build all 79 pages from versioned page-specific sources + shared parts.

No raschet-old, network, published-HTML input, or import-time writes.
Postprocessing runs on this same --site tree; browser QA is --test.
"""
import json
import shutil
import subprocess
import sys
from pathlib import Path
from html import escape
from extract_sources import render_files
from site_common import (BASE_URL, DEFAULT_SITE, LINK_MAP, NEW_TOOL_SLUGS, PARTS, REPO, SLUG_MAP, SOURCES, read, safe_destination, site_parser, write, rewrite_links, validate_manifest)

SOURCE_FILES = ("shell.html", "head.html", "body.html", "scripts.html", "page.css")

def render_source(sources, page, parts=PARTS):
    directory = Path(sources) / "pages" / page["source"]
    return render_files({name: read(directory / name) for name in SOURCE_FILES}, parts, page["path"])

def render_redirect(item):
    target, title = escape(item["target"], quote=True), escape(item["title"])
    return '<!DOCTYPE html>\n<html lang="ru"><head><meta charset="UTF-8">\n<meta http-equiv="refresh" content="0; url=%s">\n<link rel="canonical" href="%s%s">\n<title>%s</title></head><body><p>Страница переехала: <a href="%s">%s%s</a></p></body></html>\n' % (target, BASE_URL, target, title, target, BASE_URL, target)

def build(site=DEFAULT_SITE, sources=SOURCES, parts=PARTS, assets=None, static=None):
    site, sources, parts = safe_destination(site), Path(sources).resolve(), Path(parts).resolve()
    assets = Path(assets or REPO / "assets").resolve()
    static = Path(static or REPO).resolve()
    for protected in (sources, parts, assets, static):
        if site == protected or site in protected.parents or protected in site.parents:
            # A dedicated _build/out below static repository is the one permitted nesting.
            if not (protected == static and site.parent == REPO / "_build" and site.name == "out"):
                raise ValueError("Output overlaps source input: " + str(protected))
    manifest = validate_manifest(json.loads(read(sources / "manifest.json")))
    required_static = manifest["static"] + ["CNAME", ".nojekyll", "robots.txt", "sitemap.xml"]
    for rel in required_static:
        if not (static / rel).is_file(): raise ValueError("Missing required static source: " + rel)
    for rel in ("analytics.js", "og-cover.png", "icon-192.png", "icon-512.png", "icon-maskable-512.png", "vendor/qrcode.min.js"):
        if not (assets / rel).is_file(): raise ValueError("Missing required asset source: " + rel)
    for filename in ("manifest.webmanifest", "privacy.js", "privacy-routes.json"):
        if not (parts / filename).is_file(): raise ValueError("Missing required shared part: " + filename)
    from integrate_rsya import sensitive_routes
    sensitive_routes(parts)
    json.loads(read(parts / "manifest.webmanifest"))
    # Validate/read every source BEFORE clearing a previously owned output tree.
    rendered = [(page["path"], render_source(sources, page, parts)) for page in manifest["pages"]]
    marker = site / ".raschet-build"
    if site.exists():
        if not marker.is_file():
            raise ValueError("Refusing to replace non-owned output (missing .raschet-build): " + str(site))
        shutil.rmtree(site)
    site.mkdir(parents=True)
    write(marker, "Generated by build_all.py; safe dedicated output only.\n")
    for rel, text in rendered:
        write(site / rel, text)
    for item in manifest["redirects"]:
        write(site / item["path"], render_redirect(item))
    shutil.copytree(assets, site / "assets")
    for rel in required_static:
        source = static / rel
        if not source.is_file(): raise ValueError("Missing required static source: " + rel)
        shutil.copyfile(source, site / rel)
    from fix_csp import process as fix_csp
    from integrate_rsya import process as rsya
    from fix_seo_meta import process as seo
    from fix_titles import process as titles
    from integrate_pwa import process as pwa
    from test_site import static_checks
    fix_csp(site)
    rsya(site, parts)
    seo(site)
    titles(site)
    pwa(site, parts)
    errors = static_checks(site, sources)
    if errors: raise ValueError("Build gate failed:\n" + "\n".join(errors))
    print("BUILD PASS:", len(rendered), "full pages in", site)
    return site

def main():
    parser = site_parser(__doc__)
    parser.add_argument("--out", type=Path, help="Alias for --site")
    parser.add_argument("--sources", type=Path, default=SOURCES)
    parser.add_argument("--parts", type=Path, default=PARTS)
    parser.add_argument("--assets", type=Path, default=REPO / "assets")
    parser.add_argument("--static", type=Path, default=REPO)
    parser.add_argument("--test", action="store_true", help="Run independent Chrome harness with strict nonzero gate")
    args = parser.parse_args()
    site = build(args.out or args.site, args.sources, args.parts, args.assets, args.static)
    if args.test:
        subprocess.run([sys.executable, str(Path(__file__).with_name("test_site.py")), "--site", str(site), "--sources", str(args.sources)], check=True)

if __name__ == "__main__":
    main()
